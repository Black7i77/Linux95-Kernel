namespace {

constexpr int32_t minimum(int32_t a, int32_t b)
{
    return a < b ? a : b;
}

constexpr int32_t maximum(int32_t a, int32_t b)
{
    return a > b ? a : b;
}

uint8_t scale_component(uint8_t value, uint8_t size)
{
    if (size == 0) {
        return 0;
    }

    if (size >= 8) {
        return value;
    }

    return static_cast<uint8_t>(
        value >> (8 - size));
}

} // namespace

uint32_t pack_color(
    const PixelFormat& format,
    Color color)
{
    const uint32_t red =
        static_cast<uint32_t>(
            scale_component(
                color.r,
                format.red_size))
        << format.red_shift;

    const uint32_t green =
        static_cast<uint32_t>(
            scale_component(
                color.g,
                format.green_size))
        << format.green_shift;

    const uint32_t blue =
        static_cast<uint32_t>(
            scale_component(
                color.b,
                format.blue_size))
        << format.blue_shift;

    return red | green | blue;
}

Rect clip_rect(
    Rect rect,
    int32_t width,
    int32_t height)
{
    if (width <= 0 ||
        height <= 0 ||
        rect.width <= 0 ||
        rect.height <= 0) {
        return Rect{0, 0, 0, 0};
    }

    const int64_t x1 =
        maximum(rect.x, 0);

    const int64_t y1 =
        maximum(rect.y, 0);

    const int64_t raw_x2 =
        static_cast<int64_t>(rect.x) +
        static_cast<int64_t>(rect.width);

    const int64_t raw_y2 =
        static_cast<int64_t>(rect.y) +
        static_cast<int64_t>(rect.height);

    const int64_t x2 =
        minimum(
            raw_x2 > INT32_MAX
                ? INT32_MAX
                : static_cast<int32_t>(raw_x2),
            width);

    const int64_t y2 =
        minimum(
            raw_y2 > INT32_MAX
                ? INT32_MAX
                : static_cast<int32_t>(raw_y2),
            height);

    if (x2 <= x1 || y2 <= y1) {
        return Rect{0, 0, 0, 0};
    }

    return Rect{
        static_cast<int32_t>(x1),
        static_cast<int32_t>(y1),
        static_cast<int32_t>(x2 - x1),
        static_cast<int32_t>(y2 - y1),
    };
}

void put_pixel(
    Framebuffer& framebuffer,
    int32_t x,
    int32_t y,
    Color color)
{
    // Bounds checks intentionally happen before address arithmetic.
    if (framebuffer.data == nullptr ||
        x < 0 ||
        y < 0 ||
        static_cast<uint32_t>(x) >= framebuffer.width ||
        static_cast<uint32_t>(y) >= framebuffer.height) {
        return;
    }

    const uint64_t row_offset =
        static_cast<uint64_t>(y) *
        framebuffer.pitch;

    const uint64_t column_offset =
        static_cast<uint64_t>(x) * 4ULL;

    volatile uint32_t* const pixel =
        reinterpret_cast<volatile uint32_t*>(
            framebuffer.data +
            row_offset +
            column_offset);

    *pixel =
        pack_color(
            framebuffer.format,
            color);
}

void fill_rect(
    Framebuffer& framebuffer,
    Rect rect,
    Color color)
{
    const Rect clipped =
        clip_rect(
            rect,
            static_cast<int32_t>(framebuffer.width),
            static_cast<int32_t>(framebuffer.height));

    for (int32_t y = 0; y < clipped.height; ++y) {
        for (int32_t x = 0; x < clipped.width; ++x) {
            put_pixel(
                framebuffer,
                clipped.x + x,
                clipped.y + y,
                color);
        }
    }
}

void draw_rect(
    Framebuffer& framebuffer,
    Rect rect,
    Color color)
{
    if (rect.width <= 0 ||
        rect.height <= 0) {
        return;
    }

    draw_line(
        framebuffer,
        rect.x,
        rect.y,
        rect.x + rect.width - 1,
        rect.y,
        color);

    draw_line(
        framebuffer,
        rect.x,
        rect.y + rect.height - 1,
        rect.x + rect.width - 1,
        rect.y + rect.height - 1,
        color);

    draw_line(
        framebuffer,
        rect.x,
        rect.y,
        rect.x,
        rect.y + rect.height - 1,
        color);

    draw_line(
        framebuffer,
        rect.x + rect.width - 1,
        rect.y,
        rect.x + rect.width - 1,
        rect.y + rect.height - 1,
        color);
}

void draw_line(
    Framebuffer& framebuffer,
    int32_t x0,
    int32_t y0,
    int32_t x1,
    int32_t y1,
    Color color)
{
    int32_t dx =
        x1 >= x0 ? x1 - x0 : x0 - x1;

    int32_t sx =
        x0 < x1 ? 1 : -1;

    int32_t dy =
        y1 >= y0 ? y0 - y1 : y1 - y0;

    int32_t sy =
        y0 < y1 ? 1 : -1;

    int32_t error =
        dx + dy;

    for (;;) {
        put_pixel(
            framebuffer,
            x0,
            y0,
            color);

        if (x0 == x1 &&
            y0 == y1) {
            break;
        }

        const int32_t twice_error =
            error * 2;

        if (twice_error >= dy) {
            error += dy;
            x0 += sx;
        }

        if (twice_error <= dx) {
            error += dx;
            y0 += sy;
        }
    }
}

void draw_char(
    Framebuffer& framebuffer,
    int32_t x,
    int32_t y,
    char c,
    Color color)
{
    uint8_t glyph =
        static_cast<uint8_t>(c);

    if (glyph < kFontFirst ||
        glyph > kFontLast) {
        glyph = static_cast<uint8_t>('?');
    }

    const uint8_t* const rows =
        kFont8x8[glyph - kFontFirst];

    for (int32_t row = 0; row < 8; ++row) {
        const uint8_t bits =
            rows[row];

        for (int32_t column = 0;
             column < 8;
             ++column) {
            const uint8_t mask =
                static_cast<uint8_t>(
                    0x80u >> column);

            if ((bits & mask) != 0) {
                put_pixel(
                    framebuffer,
                    x + column,
                    y + row,
                    color);
            }
        }
    }
}

void draw_text(
    Framebuffer& framebuffer,
    int32_t x,
    int32_t y,
    const char* text,
    Color color)
{
    if (text == nullptr) {
        return;
    }

    const int32_t initial_x = x;

    while (*text != '\0') {
        if (*text == '\n') {
            x = initial_x;
            y += 8;
            ++text;
            continue;
        }

        draw_char(
            framebuffer,
            x,
            y,
            *text,
            color);

        x += 8;
        ++text;
    }
}

